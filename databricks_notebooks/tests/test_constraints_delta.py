def test_generated_ddl_applies_and_is_visible_in_the_metadata(constrained):
    spark = constrained
    properties = set()
    for layer, table in TABLE_DDL:
        properties |= _properties(spark, _full(layer, table))
    for layer, table, rule_id in q.ddl_targets():
        assert q.constraint_property(table, rule_id) in properties


def test_repeated_deployment_does_not_duplicate_constraints(constrained):
    spark = constrained
    properties = set()
    for layer, table in TABLE_DDL:
        properties |= _properties(spark, _full(layer, table))
    # Feeding the observed properties back makes the plan empty: the logical
    # deployment is idempotent, and no constraint is added twice.
    assert q.ddl_statements(CATALOG, properties) == []
    names = [name for name in properties if name.startswith("delta.constraints.")]
    assert len(names) == len(q.ddl_targets()) == 10


def test_valid_rows_are_written(constrained):
    spark = constrained
    _insert(spark, _full("silver", "offers_indeed"), "'1', 10.0, 20.0")
    _insert(spark, _full("silver", "offers_indeed"), "'2', NULL, NULL")
    _insert(spark, _full("silver", "offers_indeed"), "'3', 5.0, NULL")
    assert spark.table(_full("silver", "offers_indeed")).count() == 3

    profile = spark.sql(
        q.profile_sql(CATALOG, "silver", "offers_indeed", "salary_range_order")
    ).collect()[0]
    assert profile["rows_total"] == 3
    assert profile["violating_rows"] == 0
    assert profile["salary_min_annual_nulls"] == 1
    assert profile["salary_max_annual_nulls"] == 2


def test_null_job_id_is_rejected(constrained):
    with pytest.raises(Exception) as error:
        _insert(constrained, _full("silver", "offers_linkedin"),
                "NULL, 10.0, 20.0")
    assert "chk_offers_linkedin_job_id_required" in str(error.value)


def test_blank_job_id_is_rejected(constrained):
    with pytest.raises(Exception) as error:
        _insert(constrained, _full("silver", "offers_linkedin"),
                "'   ', 10.0, 20.0")
    assert "chk_offers_linkedin_job_id_required" in str(error.value)


def test_missing_salary_is_valid_and_inverted_is_rejected(constrained):
    spark = constrained
    table = _full("silver", "offers_multi_site")
    _insert(spark, table, "'1', NULL, 10.0")
    _insert(spark, table, "'2', 10.0, NULL")
    _insert(spark, table, "'3', NULL, NULL")
    with pytest.raises(Exception) as error:
        _insert(spark, table, "'4', 20.0, 10.0")
    assert "chk_offers_multi_site_salary_range_order" in str(error.value)
    assert spark.table(table).count() == 3


def test_gold_accepts_valid_dates_and_rejects_an_inverted_range(constrained):
    spark = constrained
    table = _full("gold", "fact_offers")
    _insert(spark, table, "'1', 10.0, 20.0, DATE '2026-01-01'")
    _insert(spark, table, "'2', NULL, NULL, NULL")
    with pytest.raises(Exception) as error:
        _insert(spark, table, "'3', 20.0, 10.0, DATE '2026-01-01'")
    assert "chk_fact_offers_salary_range_order" in str(error.value)
    assert spark.table(table).count() == 2

    dates = spark.sql(
        q.profile_sql(CATALOG, "gold", "fact_offers", "posted_date_contract")
    ).collect()[0]
    assert dates["rows_total"] == 2
    assert dates["violating_rows"] == 0
    assert dates["min_date"] is not None
    assert dates["max_date"] is not None


def test_profile_query_counts_violations(constrained):
    spark = constrained
    table = _full("silver", "offers_infojobs")
    # The profile measures a table whose constraint is not applied (the state
    # of a rollback): the DDL inverse is used, not a hand-written DROP.
    for statement in q.rollback_statements(CATALOG):
        if "offers_infojobs" in statement:
            spark.sql(statement)
    try:
        _insert(spark, table, "NULL, 10.0, 20.0")
        _insert(spark, table, "'2', 30.0, 10.0")
        _insert(spark, table, "'3', 1.0, 2.0")
        job = spark.sql(
            q.profile_sql(CATALOG, "silver", "offers_infojobs",
                          "job_id_required")
        ).collect()[0]
        salary = spark.sql(
            q.profile_sql(CATALOG, "silver", "offers_infojobs",
                          "salary_range_order")
        ).collect()[0]
        assert job["rows_total"] == 3
        assert job["violating_rows"] == 1
        assert job["job_id_nulls"] == 1
        assert salary["violating_rows"] == 1
    finally:
        spark.sql(f"DELETE FROM {table}")
        for statement in q.ddl_statements(CATALOG):
            if "offers_infojobs" in statement:
                spark.sql(statement)


def test_rollback_removes_the_constraint_and_the_forward_readds_it(constrained):
    spark = constrained
    table = _full("silver", "offers_multi_site")
    drop = next(
        statement for statement in q.rollback_statements(CATALOG)
        if "offers_multi_site" in statement and "job_id_required" in statement
    )
    spark.sql(drop)
    assert q.constraint_property(
        "offers_multi_site", "job_id_required"
    ) not in _properties(spark, table)
    # Without the constraint the invalid row enters: the inverse really undoes it.
    _insert(spark, table, "NULL, 1.0, 2.0")
    spark.sql(f"DELETE FROM {table} WHERE job_id IS NULL")
    add = q.add_constraint_sql(CATALOG, "silver", "offers_multi_site",
                               "job_id_required")
    spark.sql(add)
    assert q.constraint_property(
        "offers_multi_site", "job_id_required"
    ) in _properties(spark, table)
    with pytest.raises(Exception) as error:
        _insert(spark, table, "NULL, 1.0, 2.0")
    assert "chk_offers_multi_site_job_id_required" in str(error.value)


def test_deferred_date_rule_generates_no_ddl():
    assert q.ddl_statements(CATALOG) == [
        statement for statement in q.ddl_statements(CATALOG)
        if "posted_date_contract" not in statement
    ]
    assert all(
        "posted_date_contract" not in statement
        for statement in q.rollback_statements(CATALOG)
    )


