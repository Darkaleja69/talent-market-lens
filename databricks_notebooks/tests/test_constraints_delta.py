def _read(name):
    with open(os.path.join(DOCS, name), encoding="utf-8") as handle:
        return handle.read()


def test_versioned_ddl_matches_the_generator():
    script = _read("constraints-ddl.sql")
    assert script == q.ddl_script()
    assert "do not \n-- edit by hand" in script or "do not edit by hand" in script
    assert script.count("\n  ADD CONSTRAINT ") == 20
    assert script.count("-- ALTER TABLE") == 20


def test_versioned_profile_queries_match_the_generator():
    script = _read("t08-profile-queries.sql")
    assert script == q.profile_script()
    assert "job_offers_dev.gold.fact_offers" in script
    assert "job_offers.silver.offers_linkedin" in script
    assert "information_schema.tables" in script
